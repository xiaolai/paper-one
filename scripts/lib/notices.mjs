/**
 * The third-party notices document, rendered from what is INSTALLED.
 *
 * Four typefaces are bundled into every build. All four are SIL Open Font
 * License 1.1, and OFL §2 makes redistribution conditional on the copyright
 * notice and the licence travelling with the copies — so a build that ships
 * the fonts and not this file does not meet the terms it relies on.
 *
 * AND THE FONTS WERE NEVER THE WHOLE OBLIGATION. This file enumerated them
 * and nothing else for as long as it existed, while every build also shipped
 * React, pdf.js, foliate-js, Lucide and the Tauri JavaScript API — MIT, ISC
 * and Apache-2.0, every one of which conditions redistribution on the licence
 * and the copyright notice travelling with the copy, in the same words the
 * OFL uses. The bundle carried their code and named none of them. A notice
 * that lists the fonts alone is not a smaller version of the right document;
 * it is a document that is wrong about what the build contains.
 *
 * Generated rather than written, and generated from `node_modules` rather than
 * from a list in this file, because a hand-kept notices file is the most
 * reliably stale document a project has: nothing fails when a font is added,
 * removed or upgraded, and the notice then describes a build that no longer
 * exists. The gate is `check-third-party-notices.test.mjs`, which since this
 * finding also holds the two lists below against `package.json`'s
 * `dependencies` — so a new runtime dependency cannot ship unnamed.
 */

export const GENERATED_BY = '<!-- Generated by `pnpm docs:notices`. Do not edit by hand. -->'

