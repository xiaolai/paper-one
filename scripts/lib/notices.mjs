/**
 * The copyright block at the head of a LICENSE, VERBATIM.
 *
 * Reproduced exactly as the package states it rather than reformatted into
 * bullets. The first attempt split on the word `Copyright`, which turned
 * `… (url) Literata-Italic[opsz,wght].ttf: Copyright …` into two entries — one
 * of them ending in a dangling filename and the other a duplicate. A notice
 * whose job is to satisfy "the copyright notice must travel with the copy" is
 * the one document where tidying the text is a defect.
 */
export function copyrightFrom(license) {
  /* No `?? ''` after the index: `split` on a string always yields at least
   * one element, and a fallback for a case that cannot happen is a branch
   * no test can reach. */
  return license.split(/\n\s*\n/)[0].trim()
}

/** The licence body — everything after the copyright block. */
export function licenseBodyFrom(license) {
  const parts = license.split(/\n\s*\n/)
  return parts.slice(1).join('\n\n').trim()
}

/**
 * The desktop's PLATFORM plugins — the table beside the fonts.
 *
 * Not a licence obligation, which is what the fonts table is: these are
 * MIT/Apache crates, and the Rust tree holds several hundred of those that
 * are not enumerated here. This is a RECORD OF A DEPENDENCY DECISION (phase
 * 20, D5): two official Tauri plugins taken for single-instance launch and a
 * remembered window, each a crate the app crate did not carry before, and
 * each named here with the version the lockfile pins so the decision and the
 * build it describes stay one thing. `lib.rs` must register every one of
 * them, and the notices gate holds that.
 */
export const BUNDLED_PLUGINS = ['tauri-plugin-single-instance', 'tauri-plugin-window-state']

/**
 * Those crates as the resolved workspace has them — name, version and the
 * licence the crate declares — from `cargo metadata`, which is the one tool
 * that knows all three. `--offline --locked`: this runs inside a test, and a
 * lockfile the metadata call quietly rewrote is the corruption
 * `dev-docs/versioning.md` records.
 */
/**
 * A bundled crate's MIT text, VENDORED under `scripts/lib/licenses/` rather
 * than read from `~/.cargo/registry/src/` — that directory exists only after
 * a build has compiled the crate, and the notices test runs before any cargo
 * step on a fresh CI machine. The vendored copy is byte-for-byte from the
 * published crate; a conditional test compares it against the registry when
 * one is present, so an upgrade cannot quietly keep the old text.
 */
export function crateLicenseFor(name, version, root = LICENSES_DIR) {
  const at = path.join(root, `${name}-${version}-MIT.txt`)
  try {
    return readFileSync(at, 'utf8')
  } catch (cause) {
    throw new Error(`${name} ${version}: no vendored licence at ${at} — copy LICENSE_MIT from the published crate`, { cause })
  }
}

export function readCrates(root, names = BUNDLED_PLUGINS, spawn = spawnSync) {
  const run = spawn(
    'cargo',
    ['metadata', '--format-version', '1', '--offline', '--locked', '--manifest-path', path.join(root, 'src-tauri', 'Cargo.toml')],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  )
  /* A spawn that never ran has `status: null` and its story in `run.error` —
   * "cargo metadata failed: null" was the whole message when cargo was not
   * on PATH. The real cause travels. */
  if (run.error) throw new Error(`cargo metadata could not run: ${run.error.message}`, { cause: run.error })
  if (run.status !== 0) throw new Error(`cargo metadata failed (exit ${run.status ?? `signal ${run.signal}`}): ${run.stderr}`)
  const packages = JSON.parse(run.stdout).packages
  return names.map((name) => {
    /* ALL matches, not the first: Cargo can resolve two versions of one
     * crate, and `find()` silently reported whichever the resolver listed
     * first — a notice naming the transitive copy while the lockfile check
     * beside it stayed green. Ambiguity is an error, not a coin toss. */
    const matches = packages.filter((one) => one.name === name)
    if (matches.length === 0) throw new Error(`${name} is not in the resolved workspace — is it still a dependency?`)
    if (matches.length > 1) {
      throw new Error(`${name} resolves to ${matches.length} versions (${matches.map((one) => one.version).join(', ')}) — name the one the app ships`)
    }
    const found = matches[0]
    /* `license` may be absent where `license-file` stands in for it (Cargo
     * supports either); say which file rather than "unknown". */
    const license = found.license ?? (found.license_file ? `see ${found.license_file}` : 'unknown')
    return { name, version: found.version, license }
  })
}

/** Where a vendored licence text lives, beside this module. */
export const LICENSES_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), 'licenses')

/**
 * Where a package installed FOR ANOTHER PACKAGE lives.
 *
 * Node's own `node_modules` walk, hand-rolled, starting from the real
 * directory of `via`. Two reasons it is not `require.resolve`:
 * `<name>/package.json` is a subpath, and a package with an `exports` map
 * that does not list it throws `ERR_PACKAGE_PATH_NOT_EXPORTED` — which is
 * every `@tauri-apps/plugin-*` and Paper's own `foliate-js` fork. And the
 * answer must not depend on the linker: under pnpm's default the parent is a
 * symlink into `.pnpm/` with its dependencies BESIDE it, under a hoisted or
 * npm tree the child sits at the root or nested, and the same walk finds all
 * three.
 */
export function packageDirFor(root, name, via = undefined) {
  return via === undefined ? path.join(root, 'node_modules', name) : packageDirThrough(root, via, name)
}

function packageDirThrough(root, via, name) {
  let dir
  try {
    dir = realpathSync(path.join(root, 'node_modules', via))
  } catch (cause) {
    throw new Error(`${name}: its parent ${via} is not installed — the notice cannot describe a package that is not here`, { cause })
  }
  for (;;) {
    const at = path.join(dir, 'node_modules', name)
    if (existsSync(path.join(at, 'package.json'))) return at
    const up = path.dirname(dir)
    if (up === dir) {
      throw new Error(`${name}: not installed anywhere ${via} can see it — is it still a dependency of ${via}?`)
    }
    dir = up
  }
}

/**
 * One installed package's name, version, licence id and licence text.
 *
 * `entry` is a bare name (the fonts, all of which publish a plain `LICENSE`)
 * or a row of `BUNDLED_LIBRARIES`. EVERY failure throws and names the path it
 * looked at: a notice that skips a package it could not read is worse than no
 * notice, because it looks complete.
 */
export function readPackage(root, entry) {
  const { name, file = 'LICENSE', license, vendored, via } = typeof entry === 'string' ? { name: entry } : entry
  const at = packageDirFor(root, name, via)
  let manifest
  try {
    manifest = JSON.parse(readFileSync(path.join(at, 'package.json'), 'utf8'))
  } catch (cause) {
    throw new Error(`${name}: not installed at ${at} — the notice cannot describe a package that is not here`, { cause })
  }
  const from = vendored === undefined ? path.join(at, file) : path.join(LICENSES_DIR, vendored)
  let text
  try {
    text = readFileSync(from, 'utf8')
  } catch (cause) {
    throw new Error(
      `${name}: no licence text at ${from} — name the file it publishes with \`file\`, or vendor one under scripts/lib/licenses/ with \`vendored\``,
      { cause },
    )
  }
  const declared = license ?? manifest.license
  if (typeof declared !== 'string' || declared === '') {
    throw new Error(`${name}: declares no licence — say which terms the build ships it under in BUNDLED_LIBRARIES`)
  }
  return { name, version: versionOf(root, name, manifest), license: declared, text }
}

/**
 * What the build actually resolves for this package.
 *
 * A GIT DEPENDENCY HAS NO VERSION. `foliate-js` is Paper's own fork pinned to
 * a commit, and its manifest says `0.0.0` — which in a notices file reads as a
 * claim about a release rather than as the absence of one. The spec in
 * `package.json` is what the install resolved, so that is what is named, and
 * it carries the SHA that identifies the code being redistributed.
 */
function versionOf(root, name, manifest) {
  const spec = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8')).dependencies?.[name]
  return typeof spec === 'string' && /^(github:|git\+|git:|https?:|file:|link:)/.test(spec) ? spec : manifest.version
}

/**
 * Packages grouped by the exact text they carry, in first-seen order.
 *
 * A Map keyed on the text, so two packages under byte-identical terms share
 * one block and two under terms that differ by so much as a copyright line do
 * NOT — which is the property that matters: three of the packages here are
 * MIT, held by Meta, John Factotum and the Tauri Apps Contributors, and a
 * grouping that keyed on the licence NAME would print one of those three
 * copyright lines and attribute all of it to whoever came first.
 */
function groupByText(packages, textOf = (one) => one.text.trimEnd()) {
  const grouped = new Map()
  for (const one of packages) {
    const text = textOf(one)
    const held = grouped.get(text)
    if (held) held.push(one)
    else grouped.set(text, [one])
  }
  return grouped
}

/**
 * The whole document.
 *
 * THE FONTS' licence TEXT is emitted once, not four times: all four packages
 * carry the same OFL 1.1 body, and repeating it would make a 700-line file
 * out of a 200-line one while hiding the part that actually differs — the
 * attributions. If a font ever arrives under a different licence, its body is
 * emitted under its own heading, so the shared-text shortcut cannot silently
 * drop a term.
 *
 * THE LIBRARIES are reproduced WHOLE instead, grouped where two packages
 * carry byte-identical text, and this difference is deliberate. Splitting a
 * licence into "the copyright block" and "the body" works for the fonts
 * because an OFL file opens with its copyright line; an MIT file opens with
 * `MIT License` and an Apache-2.0 file has no per-package copyright line at
 * all. A heuristic that guessed where the copyright block starts would be
 * wrong about at least one of the five licences here, and being wrong about
 * where a copyright notice ends is the one defect this document cannot carry.
 */
export function renderNotices(packages, libraries = [], crates = []) {
  const lines = [
    GENERATED_BY,
    '',
    '# Third-party notices',
    '',
    'Paper redistributes the typefaces and the software below. They are covered by',
    'their own licences, whose terms require this notice to travel with every copy.',
    '',
    '## Typefaces',
    '',
    '| Package | Version | Licence |',
    '| --- | --- | --- |',
  ]
  for (const one of packages) lines.push(`| \`${one.name}\` | ${one.version} | ${one.license} |`)
  lines.push('')
  if (libraries.length > 0) {
    lines.push('## JavaScript libraries')
    lines.push('')
    lines.push('The application code every build ships — the packages Paper depends on and')
    lines.push('the ones those bring with them. Each licence is reproduced whole below,')
    lines.push('under the packages it covers; where a package offers a choice of terms, the')
    lines.push('table names the ones this copy travels under. A dependency that reaches no')
    lines.push('build is not listed — `scripts/lib/notices.mjs` records which, and the')
    lines.push('notices test walks what is installed to hold this list to it.')
    lines.push('')
    lines.push('| Package | Version | Licence |')
    lines.push('| --- | --- | --- |')
    for (const one of libraries) lines.push(`| \`${one.name}\` | ${one.version} | ${one.license} |`)
    lines.push('')
    for (const [text, sharing] of groupByText(libraries)) {
      lines.push(`### ${sharing.map((one) => `\`${one.name}\``).join(', ')}`)
      lines.push('')
      lines.push(`${[...new Set(sharing.map((one) => one.license))].join(', ')}, reproduced whole:`)
      lines.push('')
      lines.push('```')
      lines.push(text)
      lines.push('```')
      lines.push('')
    }
  }
  if (crates.length > 0) {
    /* The sibling table. Recorded, not owed — see `BUNDLED_PLUGINS`. */
    lines.push('## Desktop platform plugins')
    lines.push('')
    lines.push('The desktop build takes these official Tauri plugins for what the platform')
    lines.push('provides and the app must not hand-roll — a single running instance, and a')
    lines.push('window that remembers itself. Their MIT terms are reproduced under')
    lines.push('Attributions below. This file enumerates the bundled typefaces, the')
    lines.push('JavaScript above and these two plugins; the wider Rust dependency graph is')
    lines.push('not enumerated here, and its crates carry a range of licences of their own')
    lines.push('(MIT and Apache-2.0 mostly, with MPL-2.0, BSD, ISC, Unicode-3.0 and Zlib')
    lines.push('among them).')
    lines.push('')
    lines.push('| Crate | Version | Licence |')
    lines.push('| --- | --- | --- |')
    for (const one of crates) lines.push(`| \`${one.name}\` | ${one.version} | ${one.license} |`)
    lines.push('')
  }
  lines.push('## Attributions')
  lines.push('')
  for (const one of packages) {
    lines.push(`### \`${one.name}\``)
    lines.push('')
    lines.push('```')
    lines.push(copyrightFrom(one.text))
    lines.push('```')
    lines.push('')
  }
  /* Each plugin's MIT text WHOLE, one per crate — the two differ in their
   * copyright line (The Tauri Programme in the Commons Conservancy vs Tauri
   * Apps Contributors), so a shared body would misattribute one of them. A
   * notice whose job is "the copyright notice travels with the copy" carried
   * only SPDX identifiers for these two until the 2026-08-28 audit said so. */
  for (const one of crates) {
    lines.push(`### \`${one.name}\``)
    lines.push('')
    lines.push('```')
    lines.push(crateLicenseFor(one.name, one.version).trimEnd())
    lines.push('```')
    lines.push('')
  }

  lines.push('## Licence text')
  lines.push('')
  for (const [body, sharing] of groupByText(packages, (one) => licenseBodyFrom(one.text))) {
    lines.push(`### ${[...new Set(sharing.map((one) => one.license))].join(', ')}`)
    lines.push('')
    lines.push(`Applies to: ${sharing.map((one) => `\`${one.name}\``).join(', ')}.`)
    lines.push('')
    lines.push('```')
    lines.push(body)
    lines.push('```')
    lines.push('')
  }
  return `${lines.join('\n').trimEnd()}\n`
}
