#!/usr/bin/env node
/**
 * Stage pdf.js's runtime data files into `public/pdfjs/`.
 *
 * pdf.js does not bundle these. It fetches them at run time from URLs it is
 * given, and without them it degrades quietly rather than failing:
 *
 *   cmaps/          character maps for CJK and other non-Latin encodings.
 *                   Absent, those PDFs render as blank boxes.
 *   standard_fonts/ the base-14 fonts. A PDF that assumes Helvetica rather
 *                   than embedding it renders with substituted metrics.
 *   wasm/           the JBIG2, JPEG 2000 and OpenJPEG decoders.
 *   iccs/           ICC colour profile handling.
 *
 * `wasm/` is not optional, whatever it looks like. A SCANNED book is a stack of
 * JBIG2 or JPX images with a text layer over them — without these decoders
 * every page fails with "JBig2 failed to initialize" and the book renders
 * blank. It was dropped once to silence a Vite complaint about pdf.js's
 * dynamic import of a sibling JS fallback, which cost a real reader every page
 * of a real book. The fallback is only reached when the wasm fails to load, so
 * the answer is to serve the wasm rather than to withhold it.
 *
 * Copied rather than imported because each is a directory of dozens to
 * hundreds of files, which no bundler import can express — pdf.js wants a base
 * URL and fetches by name.
 *
 * Staged to `vendor/`, NOT `public/`. Vite treats a dynamic import that
 * resolves into publicDir as an error, and pdf.js dynamically imports the
 * `*_nowasm_fallback.js` beside each decoder — which it always needs on macOS,
 * where the wasm uses relaxed SIMD that WebKit cannot compile. The
 * `paper:pdfjs-assets` plugin in vite.config.ts serves this directory at
 * `/pdfjs/` instead.
 *
 * Not committed: it is a copy of a dependency, regenerated by this script.
 * Runs from `predev` and `prebuild`, so a fresh clone gets it without anyone
 * having to know it exists.
 */
import { cp, mkdir, rm, access } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'vendor', 'pdfjs')

/* Resolved through Node rather than assembled from a path, so pnpm's
 * content-addressed layout — where the package is NOT at the top of
 * node_modules — resolves correctly. */
const require = createRequire(import.meta.url)
const pdfjsRoot = join(dirname(require.resolve('pdfjs-dist/package.json')))

const DIRECTORIES = ['cmaps', 'standard_fonts', 'wasm', 'iccs']

async function main() {
  await rm(target, { recursive: true, force: true })
  await mkdir(target, { recursive: true })

  const copied = []
  for (const name of DIRECTORIES) {
    const from = join(pdfjsRoot, name)
    try {
      await access(from)
    } catch {
      // A future pdf.js may drop one of these. Skipping is correct; failing
      // the build over an optional data directory is not.
      continue
    }
    await cp(from, join(target, name), { recursive: true })
    copied.push(name)
  }

  if (copied.length === 0) {
    // Every one missing means the resolution is wrong, not that pdf.js changed.
    throw new Error(`sync-pdfjs-assets: nothing copied from ${pdfjsRoot}`)
  }
  console.log(`sync-pdfjs-assets: staged ${copied.join(', ')} into vendor/pdfjs/`)
}

await main()
