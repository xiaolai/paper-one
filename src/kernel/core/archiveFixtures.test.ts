import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import type { IndexedBook } from './bookIndex'
import type { Card } from './cards'
import type { Mark } from './marks'
import { exportMarks, parseArchive, toMarkdown } from './marksArchive'
import { exportTags, parseArchive as parseTagArchive } from './tagArchive'

/**
 * THE FILES A READER ALREADY HOLDS, as bytes.
 *
 * An archive is read again on the day everything else has failed, possibly years
 * after the build that wrote it, so the format is held by what such a file
 * actually contains and not by a round trip through the same code, which stays
 * green whatever that code starts to write.
 *
 * `tests/fixtures/archives/` was generated by the code as it stood BEFORE these
 * modules moved out of the kernel, from the made-up library below. Never
 * regenerate it to make this pass: a difference here is a change of format, and
 * every file already on a reader's disk is on the other side of it.
 */

const fixture = (name: string): string =>
  readFileSync(fileURLToPath(new URL(`../../../tests/fixtures/archives/${name}`, import.meta.url)), 'utf8')

const AT = Date.UTC(2026, 0, 2, 3, 4, 5)

const BOOKS: readonly IndexedBook[] = [
  {
    bookId: 'book-one',
    title: 'The Invented Harbour',
    author: 'A. Nobody',
    addedAt: 1,
    contentHash: 'a'.repeat(64),
    tags: ['Sea', 'To reread'],
  } as IndexedBook,
  { bookId: 'book-two', title: '虚构之书', author: '', addedAt: 2, tags: ['小说'] } as IndexedBook,
  { bookId: 'book-three', title: 'Left Untouched', author: 'B. Nobody', addedAt: 3 } as IndexedBook,
]

const MARK = (over: Partial<Mark>): Mark =>
  ({
    id: 'm',
    bookId: 'book-one',
    cfi: 'epubcfi(/6/4!/4/2/1:0)',
    sectionIndex: 1,
    text: 'The tide came in sideways.',
    prefix: 'At dawn ',
    suffix: ' Nobody minded.',
    note: 'Is this the narrator lying?',
    kind: 'highlight',
    tint: 'yellow',
    style: 'fill',
    chapter: 'Chapter 1',
    createdAt: AT,
    ...over,
  }) as Mark

const MARKS: readonly Mark[] = [
  MARK({ id: 'm1' }),
  MARK({ id: 'm2', cfi: 'epubcfi(/6/6!/4/2/1:0)', sectionIndex: 2, text: 'Second passage', note: '', tint: 'green' }),
  MARK({ id: 'm3', kind: 'bookmark', cfi: 'epubcfi(/6/8!/4/2)', sectionIndex: 3, text: '', prefix: '', suffix: '', note: '' }),
  MARK({
    id: 'm4',
    cfi: '',
    sectionIndex: 0,
    text: 'A passage from another edition',
    unplaced: { reason: 'foreign-build', fromBook: 'book-old' },
  }),
  MARK({ id: 'm5', bookId: 'book-two', cfi: 'epubcfi(/6/2!/4/2/1:3)', sectionIndex: 0, text: '潮水从侧面涌来。', note: '# 不是标题' }),
]

const CARD = (over: Partial<Card>): Card =>
  ({
    id: 'c',
    bookId: 'book-one',
    kind: 'Recall',
    body: 'Who keeps the harbour?',
    answer: 'Nobody',
    source: 'Chapter 1',
    cfi: 'epubcfi(/6/4!/4/2/1:0)',
    createdAt: AT,
    ...over,
  }) as Card

const CARDS: readonly Card[] = [CARD({ id: 'c1' }), CARD({ id: 'c2', kind: 'Idea', body: 'Tides as memory', answer: '', cfi: null })]

describe('marginalia archives already on a reader\'s disk', () => {
  const held = fixture('marks-v1.json')

  it('are still what this library exports, byte for byte', () => {
    expect(JSON.stringify(exportMarks(BOOKS, MARKS, CARDS), null, 2)).toBe(held)
  })

  it('read and write back byte for byte', () => {
    const parsed = parseArchive(held)
    expect(parsed).not.toBeNull()
    expect(JSON.stringify(parsed, null, 2)).toBe(held)
  })

  it('hold every class of row, or the two checks above prove less than they say', () => {
    const parsed = parseArchive(held)
    expect(parsed?.books.map((book) => [book.bookId, book.marks.length, book.cards.length])).toEqual([
      ['book-one', 4, 2],
      ['book-two', 1, 0],
    ])
    expect(parsed?.books[0]?.contentHash).toBe('a'.repeat(64))
    expect(parsed?.books[0]?.marks.map((mark) => mark.kind)).toContain('bookmark')
    expect(parsed?.books[0]?.marks[3]?.unplaced).toEqual({ reason: 'foreign-build', fromBook: 'book-old' })
  })

  it('render the same reading copy', () => {
    expect(toMarkdown(exportMarks(BOOKS, MARKS, CARDS))).toBe(fixture('marks-v1.md'))
  })
})

describe('tag archives already on a reader\'s disk', () => {
  const held = fixture('tags-v1.json')

  it('are still what this library exports, byte for byte', () => {
    expect(JSON.stringify(exportTags(BOOKS), null, 2)).toBe(held)
  })

  it('read and write back byte for byte', () => {
    const parsed = parseTagArchive(held)
    expect(parsed).not.toBeNull()
    expect(JSON.stringify(parsed, null, 2)).toBe(held)
    expect(parsed?.books.map((book) => book.tags)).toEqual([['Sea', 'To reread'], ['小说']])
  })
})
